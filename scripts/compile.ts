// Build one self-contained executable per platform, with the web app embedded.
// Usage: bun scripts/compile.ts            (all targets)
//        bun scripts/compile.ts darwin-arm64 linux-x64
import { readdirSync, statSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const dist = join(root, "web", "dist");
const out = join(root, "dist");

const ALL = ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64", "windows-x64"];
const targets = process.argv.slice(2).length ? process.argv.slice(2) : ALL;

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

// A generated module that imports every built web file so `bun build --compile` embeds it.
const files = walk(dist);
const lines = files.map((f, i) => `import f${i} from ${JSON.stringify(relative(join(root, "server", "src"), f).split("\\").join("/"))} with { type: "file" };`);
const map = files.map((f, i) => `  ${JSON.stringify("/" + relative(dist, f).split("\\").join("/"))}: f${i},`);
await writeFile(join(root, "server", "src", "assets.gen.ts"), `// Generated by scripts/compile.ts. Do not edit.\n${lines.join("\n")}\n\nexport default {\n${map.join("\n")}\n} as unknown as Record<string, string>;\n`);

await mkdir(out, { recursive: true });
for (const t of targets) {
  const name = `control-center-${t}${t.startsWith("windows") ? ".exe" : ""}`;
  console.log(`Building ${name}…`);
  const p = Bun.spawn(["bun", "build", "--compile", "--minify", `--target=bun-${t}`, join(root, "server", "src", "compile-entry.ts"), "--outfile", join(out, name)], {
    cwd: root,
    stdout: "inherit",
    stderr: "inherit",
  });
  if ((await p.exited) !== 0) process.exit(1);
}
console.log(`Done. Executables are in ${relative(process.cwd(), out) || "."}/`);
